#!/usr/bin/env bash
# compat — run the real-client e2e suite (TestClients, TestRelay) against a
# live upstream and record the results in docs/compat/<date>.md plus the
# table in docs/compat/README.md.
#
#   PLUGRELAY_E2E_BASE, PLUGRELAY_E2E_KEY   required (the key stays in the environment)
#   PLUGRELAY_E2E_MODEL, PLUGRELAY_E2E_CHAT_MODEL   optional, see test/e2e/clients_test.go
#   PLUGRELAY_COMPAT_UPSTREAM   how the report names the upstream (its URL is never written)
#   PLUGRELAY_COMPAT_DATE       report date (default: today, UTC)
#   PLUGRELAY_COMPAT_EVENTS     keep the `go test -json` events here; when the file
#                               already exists, only re-render the report from it
#
# Exit status: the suite's (0 = every case passed or skipped).
set -u
cd "$(dirname "$0")/.." || exit 1
if [ -z "${PLUGRELAY_E2E_BASE:-}" ] || [ -z "${PLUGRELAY_E2E_KEY:-}" ]; then
  echo "compat: set PLUGRELAY_E2E_BASE and PLUGRELAY_E2E_KEY" >&2
  exit 2
fi
command -v jq >/dev/null || { echo "compat: jq is required" >&2; exit 2; }

date=${PLUGRELAY_COMPAT_DATE:-$(date -u +%F)}
upstream=${PLUGRELAY_COMPAT_UPSTREAM:-an OpenAI-compatible upstream}
out=docs/compat/$date.md
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

ver() { if command -v "$1" >/dev/null; then "$1" --version 2>/dev/null | head -n 1; else echo "not installed"; fi; }
claude_ver=$(ver claude)
codex_ver=$(ver codex)
relay_ver="plugrelay $(git describe --tags --always --dirty 2>/dev/null || echo 'uncommitted tree')"
go_ver=$(go env GOVERSION)

events=${PLUGRELAY_COMPAT_EVENTS:-$tmp/events.json}
if [ -s "$events" ] && [ -n "${PLUGRELAY_COMPAT_EVENTS:-}" ]; then
  echo "compat: re-rendering from $events" >&2
  status=$(jq -s 'if any(.[]; .Action == "fail") then 1 else 0 end' "$events")
else
  echo "compat: running TestClients and TestRelay (takes minutes)…" >&2
  PLUGRELAY_E2E_CLIENTS=1 go test -tags e2e -count=1 -timeout 60m -json \
    -run '^(TestClients|TestRelay)$' ./test/e2e/ >"$events"
  status=$?
fi

# One row per finished subtest, fields split by US (0x1f): name, action, seconds, model, note.
jq -r -s '
  def outputs($t): [.[] | select(.Test == $t and .Action == "output") | .Output];
  . as $all
  | [.[] | select(.Test != null and (.Test | contains("/")) and (.Action == "pass" or .Action == "fail" or .Action == "skip"))]
  | .[] | . as $e
  | ($all | outputs($e.Test)) as $o
  | ($o | map(select(test("compat: model=")) | capture("compat: model=(?<m>\\S+)").m) | first // "") as $model
  | ($o | map(select(test("^\\s+\\S+\\.go:[0-9]+: ")) | sub("^\\s+\\S+\\.go:[0-9]+: "; "") | rtrimstr("\n"))
        | map(select(startswith("compat:") | not)) | last // "") as $note
  | [$e.Test, $e.Action, ($e.Elapsed // 0 | tostring), $model, ($note | gsub("\\|"; "/") | .[0:160])] | join("\u001f")
'  "$events" >"$tmp/rows.txt" || exit 1

# Client subtests per route, plus a client skipped as a whole (not on PATH).
client_rows=$'^TestClients/[^/]+/|^TestClients/[^/\x1f]+\x1fskip'
dur() { awk -v s="$1" 'BEGIN { s = int(s + 0.5); if (s >= 60) printf "%dm%02ds", s / 60, s % 60; else printf "%ds", s }'; }
result() { case $1 in pass) echo "pass" ;; fail) echo "**fail**" ;; *) echo "skip" ;; esac; }

{
  echo "# Client compatibility run, $date"
  echo
  echo "Generated by \`scripts/compat.sh\`; how to read and rerun it: [README](README.md)."
  echo
  echo "| | |"
  echo "|-|-|"
  echo "| relay | $relay_ver ($go_ver) |"
  echo "| upstream | $upstream |"
  echo "| Claude Code | $claude_ver |"
  echo "| Codex | $codex_ver |"
  echo
  echo "## Real clients (\`TestClients\`)"
  echo
  echo "Each client writes and runs a small Python program through the relay. On the"
  echo "chat-only route every request is converted (Anthropic Messages or OpenAI"
  echo "Responses → Chat Completions)."
  echo
  echo "| client | route | upstream model | result | duration | note |"
  echo "|-|-|-|-|-|-|"
  grep -E "$client_rows" "$tmp/rows.txt" | while IFS=$'\x1f' read -r name action secs model note; do
    IFS=/ read -r _ client route <<<"$name"; route=${route:-all_routes}
    echo "| $client | ${route//_/ } | ${model:--} | $(result "$action") | $(dur "$secs") | $note |"
  done
  echo
  echo "## Protocols (\`TestRelay\`)"
  echo
  echo "| case | result | duration | note |"
  echo "|-|-|-|-|"
  grep -E '^TestRelay/' "$tmp/rows.txt" | while IFS=$'\x1f' read -r name action secs _ note; do
    case=${name#TestRelay/}
    echo "| ${case//_/ } | $(result "$action") | $(dur "$secs") | $note |"
  done
} >"$out"

# The index: this date's rows replace any earlier ones of the same date.
readme=docs/compat/README.md
rows=$(grep -E "$client_rows" "$tmp/rows.txt" | while IFS=$'\x1f' read -r name action secs model _; do
  IFS=/ read -r _ client route <<<"$name"; route=${route:-all_routes}
  case $client in claude-code) v=$claude_ver ;; codex) v=$codex_ver ;; *) v="" ;; esac
  echo "| $date | $client | $v | ${route//_/ } | ${model:--} | $(result "$action") | $(dur "$secs") | $relay_ver | [report]($date.md) |"
done)
awk -v rows="$rows" -v date="$date" '
  /<!-- compat:rows/ { hdr = 2; print; next }
  index($0, "](" date ".md)") { next }
  { print }
  hdr > 0 && --hdr == 0 && rows != "" { print rows }' "$readme" >"$tmp/readme" && cp "$tmp/readme" "$readme"

echo "compat: wrote $out and updated $readme (go test exit $status)" >&2
exit $status
