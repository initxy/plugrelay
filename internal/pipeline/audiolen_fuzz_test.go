package pipeline

import (
	"bytes"
	"testing"
)

// The duration readers never panic on any header, and no file is priced
// shorter than its bytes at floorKbps, whatever its header claims.
func FuzzAudioDuration(f *testing.F) {
	f.Add([]byte("RIFF\x24\x00\x00\x00WAVEfmt \x10\x00\x00\x00\x01\x00\x01\x00\x44\xac\x00\x00\x88\x58\x01\x00\x02\x00\x10\x00data\x00\x00\x00\x00"), []byte{}, int64(1000))
	f.Add([]byte("fLaC\x00\x00\x00\x22\x10\x00\x10\x00\x00\x00\x00\x00\x00\x00\x0a\xc4\x42\xf0\x00\x00\x00\x00"), []byte{}, int64(10))
	f.Add([]byte("OggS\x00\x02\x00\x00\x00\x00\x00\x00\x00\x00\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x01\x13\x01vorbis\x00\x00\x00\x00\x02\x44\xac\x00\x00"), []byte("OggS\x00\x04\x00\x00\x10\x00\x00\x00\x00\x00"), int64(100))
	f.Add([]byte("\x00\x00\x00\x18ftypisom\x00\x00\x00\x00isommp41\x00\x00\x00\x6cmoov\x00\x00\x00\x64mvhd\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x03\xe8\x00\x00\x27\x10"), []byte{}, int64(100))
	f.Add([]byte("\x1a\x45\xdf\xa3\x9f\x42\x86\x81\x01\x18\x53\x80\x67\x01\x00\x00\x00\x00\x00\x00\x10\x15\x49\xa9\x66\x8a\x2a\xd7\xb1\x83\x0f\x42\x40\x44\x89\x84\x46\x1c\x40\x00"), []byte{}, int64(100))
	f.Add([]byte("ID3\x04\x00\x00\x00\x00\x00\x00\xff\xfb\x90\x64\x00\x00\x00\x00Xing\x00\x00\x00\x01\x00\x00\x01\x00"), []byte{}, int64(5000))
	f.Fuzz(func(t *testing.T, head, tail []byte, size int64) {
		if size >= 0 && size < 1<<40 {
			if ms := audioMs(head, tail, size); ms < size*8/floorKbps {
				t.Fatalf("%d ms for %d bytes", ms, size)
			}
		}
		_ = wavMs(head, size)
		_ = flacMs(head)
		_ = oggMs(head, tail)
		_ = mp4Ms(head, tail)
		_ = webmMs(head)
		_ = mp3Ms(head, size)
		p := &audioProbe{}
		_, _ = p.tee(bytes.NewReader(append(head, tail...))).Read(make([]byte, 1<<16))
		_ = p.ms()
	})
}
