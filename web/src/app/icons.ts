import {
  Activity,
  BarChart3,
  Bell,
  CalendarClock,
  Gauge,
  History,
  KeyRound,
  LayoutGrid,
  ListTree,
  LogIn,
  Megaphone,
  MessageSquareText,
  Package,
  Percent,
  Plug,
  Puzzle,
  Receipt,
  Route,
  Server,
  Settings,
  Tag,
  Ticket,
  Users,
  Wallet,
  type LucideIcon,
} from "lucide-react";

/** Menu and search icons by name; anything unknown falls back to the puzzle piece. */
const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  bell: Bell,
  calendar: CalendarClock,
  chart: BarChart3,
  features: LayoutGrid,
  gauge: Gauge,
  history: History,
  key: KeyRound,
  list: ListTree,
  login: LogIn,
  megaphone: Megaphone,
  message: MessageSquareText,
  package: Package,
  percent: Percent,
  plug: Plug,
  puzzle: Puzzle,
  receipt: Receipt,
  route: Route,
  server: Server,
  settings: Settings,
  tag: Tag,
  ticket: Ticket,
  users: Users,
  wallet: Wallet,
};

export function iconFor(name: string): LucideIcon {
  return ICONS[name] ?? Puzzle;
}
